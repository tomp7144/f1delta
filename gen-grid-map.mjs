/* ============================================================
   F1 DELTA — bake the current-grid code→slug map
   Reads data/drivers/index.json, keeps active drivers (lastSeason
   >= 2026), writes public/grid-map.js as window.F1_GRID. The home
   uses this to make race/standings rows clickable WITHOUT a runtime
   fetch. ~22 entries; auto-correct slugs (no hand-typing). Run by
   the same Action as the other bakes.

   Run locally:  node gen-grid-map.mjs
   ============================================================ */
import { readFile, writeFile, mkdir } from "node:fs/promises";

const SEASON = 2026;
try {
  const idx = JSON.parse(await readFile("data/drivers/index.json", "utf8"));
  const active = (idx.drivers || []).filter((d) => d.lastSeason >= SEASON && d.code);
  const map = {};
  for (const d of active) map[d.code.toUpperCase()] = d.driverId; // last wins on dup code
  await mkdir("public", { recursive: true });
  const out =
    "/* AUTO-GENERATED by gen-grid-map.mjs — current grid code→slug.\n" +
    "   Do not hand-edit; re-run the script (or let the cron bake it). */\n" +
    "window.F1_GRID = " + JSON.stringify(map, null, 2) + ";\n";
  await writeFile("public/grid-map.js", out);
  console.log(`[F1Delta] wrote public/grid-map.js with ${Object.keys(map).length} drivers`);
} catch (err) {
  console.error("[F1Delta] grid-map bake failed:", err.message);
  process.exit(1);
}
